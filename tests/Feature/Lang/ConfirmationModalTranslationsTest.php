/**
 * Guards the confirmation-modal translation keys.
 *
 * Every modal string used by the shared confirmation modal must resolve to
 * non-empty copy in all shipped locales (en, es, fr), so a future edit that
 * renames or drops a key fails here instead of rendering raw key names.
 */
it('resolves every modal confirmation key in all locales', function (string $key): void {
    foreach (['en', 'es', 'fr'] as $locale) {
        $value = __("admin.$key", ['name' => 'Test'], $locale);

